/**
 * Verify the live Web GUI is serving this plugin's current client bundle.
 *
 * The bundled client artifact is a plain file in this linked package. The Host
 * client-modules service serves it at `/plugins/??<id>/client.js&rev=<rev>`,
 * where `<rev>` is a SHA-1 over the artifact's mtime/ctime/size. The client HMR
 * transport stat-polls that artifact and republishes it on change, so a 200 for
 * the freshly computed rev proves both:
 *
 *   1. the bundle the page will fetch is the one just built here, and
 *   2. the HMR transport has published that generation (no restart needed).
 *
 * Runs read-only against the local GUI; pass `--url` to point elsewhere and
 * `--wait <ms>` to allow the poller time to notice a fresh build. The default
 * target is `$DSH_WEB_URL` (set inside a DSH session) or the historical desktop
 * port.
 *
 * Usage: pnpm exec tsx scripts/verify-live.ts [--url http://127.0.0.1:56750] [--wait 8000]
 */
import { createHash } from 'node:crypto';
import { readFileSync, statSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { LOGOS } from '../src/logos';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CLIENT = resolve(ROOT, 'client.js');
const PACKAGE_NAME = 'dsh-model-logos';

const args = process.argv.slice(2);
const valueOf = (flag: string, fallback: string): string => {
  const at = args.indexOf(flag);
  const value = args[at + 1];
  return at >= 0 && value !== undefined ? value : fallback;
};
const baseUrl = valueOf('--url', process.env.DSH_WEB_URL ?? 'http://127.0.0.1:49892').replace(/\/$/, '');
const waitMs = Number(valueOf('--wait', '8000'));

/** Artifact revision as computed by the Host client-modules service. */
function artifactRevision(path: string): string {
  const stat = statSync(path);
  const hash = createHash('sha1').update('plugin-artifact').update('\0');
  for (const part of [String(stat.mtimeMs), String(stat.ctimeMs), String(stat.size)]) {
    hash.update(`${String(Buffer.byteLength(part))}:`).update(part);
  }
  return hash.digest('hex').slice(0, 12);
}

const source = readFileSync(CLIENT, 'utf8');
const rev = artifactRevision(CLIENT);
const url = `${baseUrl}/plugins/??${PACKAGE_NAME}/client.js&rev=${rev}`;
const deadline = Date.now() + waitMs;

let response: Response | null = null;
let body = '';
while (Date.now() < deadline) {
  try {
    const candidate = await fetch(url);
    if (candidate.ok) {
      response = candidate;
      body = await candidate.text();
      break;
    }
  } catch {
    // The GUI may be between restarts; retry until the deadline.
  }
  await new Promise<void>((done) => {
    setTimeout(done, 400);
  });
}

if (response === null) {
  console.error(`error: ${url} did not return 200 within ${waitMs}ms — the HMR transport has not published rev ${rev}`);
  process.exit(1);
}

const expectations: ReadonlyArray<readonly [RegExp, string]> = [
  [/Generated by scripts\/build\.ts from src\/\*\*\/\*\.ts — do not edit\./, 'client bundle header'],
  [/id: 'dsh-model-logos'/, 'browser module id'],
  [/conversation\.input\.model\.label/, 'label slot registration'],
  [/priority: -1/, 'shadowing priority'],
  [/dshml-root/, 'label stylesheet class'],
];
for (const [pattern, label] of expectations) {
  if (!pattern.test(body)) {
    console.error(`error: served bundle is missing ${label}`);
    process.exit(1);
  }
}
const artworkKeys = Object.keys(LOGOS);
console.log(`OK ${url}`);
console.log(`  served bytes: ${body.length} (built artifact: ${source.length})`);
console.log(`  rev: ${rev}`);
console.log(`  artwork entries: ${artworkKeys.length}${artworkKeys.length > 0 ? ' — ' + artworkKeys.join(', ') : ''}`);
