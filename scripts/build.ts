/**
 * Build the two shipped entry points from the TypeScript sources:
 *
 *   `client.js` — the browser module the DSH client loader evaluates. It is one
 *                 esbuild bundle wrapped in the `window.__ModuleLoader__` factory
 *                 contract, with React left external (the loader's `require`
 *                 resolves the shell's platform module table).
 *   `index.js`  — the host half, an ES module that keeps
 *                 `@deepseek-ai/schemastery` external so the host resolves it
 *                 from this package's dependencies.
 *
 * Artwork and matcher invariants are validated here rather than at runtime, so a
 * broken logo, an unreachable key or an unsafe SVG fails the build instead of a
 * user's settings page.
 *
 * `--check` rebuilds both artifacts in memory and compares them with the
 * committed files, exiting non-zero when either is stale. Generated artifacts are
 * never written in that mode.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

import { LOGOS as MANUAL_LOGOS } from '../src/logos/manual';
import { LOGOS as OFFICIAL_LOGOS } from '../src/logos/official.generated';
import { SHARED_VENDOR_MARKS } from '../src/logos/groups';
import { LOGO_RANKS } from '../src/logos/ranking';
import { LOGO_KEYS, MODEL_RULES, PICKER_ONLY_KEYS, PROVIDER_RULES, VENDOR_CHANNELS, VENDOR_RULES } from '../src/match';
import { letterTile } from '../src/artwork';
import { DSHML_NAV_ICON_CSS, DSHML_NAV_ICON_SVG, DSHML_NAV_MARKER } from '../src/nav-icon';
import type { BrandLogo, LogoGroup, LogoSet } from '../src/types';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CLIENT_OUT = resolve(ROOT, 'client.js');
const HOST_OUT = resolve(ROOT, 'index.js');

const CLIENT_HEADER = '// Generated by scripts/build.ts from src/**/*.ts — do not edit. Run `pnpm run build`.';
const HOST_HEADER = '// Generated by scripts/build.ts from src/host.ts — do not edit. Run `pnpm run build`.';

/** Browser module id the DSH client-modules kernel registers the bundle under. */
const BUNDLE_ID = 'dsh-model-logos';

/** Platform modules resolved through the loader's `factory(require)` argument. */
const CLIENT_EXTERNALS = ['react', 'react-dom', 'react-dom/client'];

/** Collected validation failures (abort the build) and warnings (report only). */
const problems: string[] = [];
const warnings: string[] = [];

/** Source sets, in the order they are documented in `docs/engineering.md`. */
const ARTWORK_SETS: ReadonlyArray<{ name: string; logos: LogoSet }> = [
  { name: 'src/logos/official.generated.ts', logos: OFFICIAL_LOGOS },
  { name: 'src/logos/manual.ts', logos: MANUAL_LOGOS },
];

/** The five characters that must be entity-escaped in generated SVG text. */
function isLogoShape(value: unknown): value is { title: string; svg: string } {
  if (value === null || typeof value !== 'object') return false;
  const candidate = value as { title?: unknown; svg?: unknown };
  return typeof candidate.title === 'string' && typeof candidate.svg === 'string';
}

/** A brand entry: title, svg and one picker group. */
function isLogo(value: unknown): value is BrandLogo {
  if (!isLogoShape(value)) return false;
  const group = (value as { group?: unknown }).group;
  return group === 'vendor' || group === 'model';
}

/** Validate one artwork set and merge it into `merged`, reporting collisions. */
function collectLogos(merged: Map<string, BrandLogo>): void {
  for (const set of ARTWORK_SETS) {
    for (const [key, value] of Object.entries(set.logos)) {
      if (!isLogo(value)) {
        problems.push(`${set.name}: logo "${key}" must be a { title, svg, group } object`);
        continue;
      }
      if (value.title.trim() === '') problems.push(`${set.name}: logo "${key}" needs a non-empty title`);
      if (!value.svg.trim().startsWith('<svg')) {
        problems.push(`${set.name}: logo "${key}" needs an svg string starting with <svg`);
        continue;
      }
      if (merged.has(key)) {
        problems.push(`${set.name}: duplicate logo key "${key}"`);
        continue;
      }
      // The XML namespace declaration is inert when the svg is inlined into HTML;
      // strip it before rejecting genuine external references.
      const withoutNamespace = value.svg.replace(/\sxmlns(?::[\w-]+)?\s*=\s*"[^"]*"/gi, '');
      if (/\sid\s*=/.test(value.svg)) {
        problems.push(`${set.name}: logo "${key}" must not use id attributes (inlined DOM would collide)`);
      }
      if (/<script/i.test(value.svg)) problems.push(`${set.name}: logo "${key}" must not contain scripts`);
      if (/\son[a-z]+\s*=/i.test(value.svg)) {
        problems.push(`${set.name}: logo "${key}" must not contain event handlers`);
      }
      if (/https?:/i.test(withoutNamespace)) {
        problems.push(`${set.name}: logo "${key}" must not reference external resources`);
      }
      merged.set(key, { title: value.title.trim(), svg: value.svg.trim(), group: value.group });
    }
  }
}

/** Validate that every matcher key has artwork and every artwork key is reachable. */
function validateCoverage(merged: Map<string, BrandLogo>): void {
  if (LOGO_KEYS.length === 0) problems.push('src/match.ts: LOGO_KEYS must not be empty');
  if (new Set(LOGO_KEYS).size !== LOGO_KEYS.length) problems.push('src/match.ts: LOGO_KEYS has duplicate entries');

  for (const key of LOGO_KEYS) {
    if (!merged.has(key)) problems.push(`logo key "${key}" has no artwork`);
  }
  for (const key of merged.keys()) {
    if (!LOGO_KEYS.includes(key)) warnings.push(`logo "${key}" is never returned by a rule`);
  }

  const ruleKeys = new Set<string>();
  for (const [key] of MODEL_RULES) ruleKeys.add(key);
  for (const [key] of PROVIDER_RULES) ruleKeys.add(key);
  for (const [key] of VENDOR_RULES) ruleKeys.add(key);
  for (const key of Object.values(VENDOR_CHANNELS)) ruleKeys.add(key);
  for (const key of PICKER_ONLY_KEYS) ruleKeys.add(key);
  for (const key of LOGO_KEYS) {
    if (!ruleKeys.has(key)) warnings.push(`logo "${key}" is never matched and is not picker-only`);
  }
  for (const key of PICKER_ONLY_KEYS) {
    if (!LOGO_KEYS.includes(key)) problems.push(`picker-only key "${key}" is not in LOGO_KEYS`);
  }

  for (const [key] of VENDOR_RULES) {
    if (!LOGO_KEYS.includes(key)) problems.push(`vendor rule key "${key}" is not in LOGO_KEYS`);
  }
  for (const [channel, key] of Object.entries(VENDOR_CHANNELS)) {
    if (!LOGO_KEYS.includes(key)) problems.push(`vendor channel "${channel}" maps to unknown key "${key}"`);
    const entry = merged.get(key);
    if (entry !== undefined && entry.group !== 'vendor' && !SHARED_VENDOR_MARKS.includes(key)) {
      problems.push(`vendor channel "${channel}" maps to model-only mark "${key}"`);
    }
  }
}

/** Validate the picker groups and the generated prominence snapshot. */
function validateGroupsAndRanks(merged: Map<string, BrandLogo>): void {
  const groups: Record<LogoGroup, string[]> = { vendor: [], model: [] };
  for (const [key, entry] of merged) {
    groups[entry.group].push(key);
  }
  for (const group of ['vendor', 'model'] as const) {
    if (groups[group].length === 0) problems.push(`artwork group "${group}" must not be empty`);
    const ranks = groups[group]
      .map((key) => LOGO_RANKS[key])
      .filter((rank): rank is number => typeof rank === 'number' && Number.isFinite(rank))
      .sort((a, b) => a - b);
    if (ranks.length !== groups[group].length) {
      problems.push(`artwork group "${group}" has keys without a prominence rank`);
    }
    for (let index = 0; index < ranks.length; index++) {
      if (ranks[index] !== index + 1) {
        problems.push(`artwork group "${group}" ranks must be contiguous from 1 (got ${ranks.join(',')})`);
        break;
      }
    }
  }
  for (const key of Object.keys(LOGO_RANKS)) {
    if (!merged.has(key)) problems.push(`prominence rank for unknown logo "${key}"`);
  }
}

/** Validate the generated letter-tile fallback that ships in the runtime. */
function validateLetterTile(): void {
  const sample = letterTile('测试');
  if (!isLogoShape(sample)) {
    problems.push('src/artwork.ts: letterTile must return { title, svg }');
    return;
  }
  if (!sample.svg.startsWith('<svg')) problems.push('src/artwork.ts: letterTile svg must start with <svg');
  if (/\sid\s*=/.test(sample.svg)) problems.push('src/artwork.ts: letterTile svg must not use id attributes');
  if (/<script|\son[a-z]+\s*=|https?:/i.test(sample.svg.replace(/\sxmlns[^=]*="[^"]*"/gi, ''))) {
    problems.push('src/artwork.ts: letterTile svg must stay self-contained');
  }
  const first = letterTile('Acme Labs', 'acme');
  const second = letterTile('Acme Labs', 'acme');
  if (first.svg !== second.svg) problems.push('src/artwork.ts: letterTile must be deterministic');
}

/** Validate the Settings-navigation glyph and the one stylesheet rule that paints it. */
function validateNavIcon(): void {
  const svg = DSHML_NAV_ICON_SVG;
  if (!svg.trim().startsWith('<svg')) problems.push('src/nav-icon.ts: nav glyph must start with <svg');
  if (!svg.includes('viewBox="0 0 16 16"')) problems.push('src/nav-icon.ts: nav glyph must be a 16x16 viewBox');
  if (!svg.includes('currentColor')) problems.push('src/nav-icon.ts: nav glyph must be drawn in currentColor');
  if (/\sid\s*=/.test(svg)) problems.push('src/nav-icon.ts: nav glyph must not use id attributes');
  if (/<script|\son[a-z]+\s*=|https?:/i.test(svg.replace(/\sxmlns[^=]*="[^"]*"/gi, ''))) {
    problems.push('src/nav-icon.ts: nav glyph must stay self-contained');
  }
  // A mask URL that is not fully percent-encoded can terminate the declaration.
  const rowSelector = '[data-dshml-nav="' + DSHML_NAV_MARKER + '"]';
  if (!DSHML_NAV_ICON_CSS.includes(rowSelector + ' > svg')) {
    problems.push('src/nav-icon.ts: nav stylesheet must hide the shipped glyph on the marked row');
  }
  if (!DSHML_NAV_ICON_CSS.includes(rowSelector + '::before')) {
    problems.push('src/nav-icon.ts: nav stylesheet must paint the glyph on the marked row');
  }
  if (!DSHML_NAV_ICON_CSS.includes('-webkit-mask:') || !DSHML_NAV_ICON_CSS.includes('mask:')) {
    problems.push('src/nav-icon.ts: nav stylesheet must paint the glyph as a CSS mask');
  }
}

/** esbuild banner/footer that adapt the ESM entry to the module-loader contract. */
function clientWrapper(): { banner: string; footer: string } {
  return {
    banner: `${CLIENT_HEADER}
window.__ModuleLoader__.load({
  id: '${BUNDLE_ID}',
  factory(require) {`,
    footer: `    return { inject: __dshml.inject, apply: __dshml.apply };
  },
});
`,
  };
}

/** Build the browser bundle text (never written to disk here). */
async function buildClient(): Promise<string> {
  const { banner, footer } = clientWrapper();
  const result = await build({
    absWorkingDir: ROOT,
    entryPoints: ['src/client.ts'],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: '__dshml',
    platform: 'browser',
    target: ['chrome120'],
    external: CLIENT_EXTERNALS,
    banner: { js: banner },
    footer: { js: footer },
    minify: false,
    sourcemap: false,
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'silent',
  });
  const output = result.outputFiles?.[0];
  if (output === undefined) throw new Error('esbuild produced no client output');
  return output.text;
}

/** Build the host ES module text (never written to disk here). */
async function buildHost(): Promise<string> {
  const result = await build({
    absWorkingDir: ROOT,
    entryPoints: ['src/host.ts'],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'node',
    target: ['node22'],
    external: ['@deepseek-ai/schemastery'],
    banner: { js: HOST_HEADER },
    minify: false,
    sourcemap: false,
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'silent',
  });
  const output = result.outputFiles?.[0];
  if (output === undefined) throw new Error('esbuild produced no host output');
  return output.text;
}

/** Assert the generated bundle still honours the module-loader contract. */
function validateClientBundle(text: string): void {
  const markers: ReadonlyArray<readonly [string, string]> = [
    ['window.__ModuleLoader__.load({', 'module-loader registration'],
    [`id: '${BUNDLE_ID}'`, 'browser module id'],
    ['factory(require) {', 'factory contract'],
    ['conversation.input.model.label', 'label slot registration'],
    ['priority: -1', 'shadowing priority'],
    ['dshml-root', 'label stylesheet class'],
    ['data-dshml-nav', 'settings nav glyph marker'],
  ];
  if (text.length < 1000) problems.push('client bundle is suspiciously small');
  for (const [marker, label] of markers) {
    if (!text.includes(marker)) problems.push(`client bundle is missing its ${label}`);
  }
}

/** Read a committed artifact, or '' when it does not exist yet. */
function readArtifact(path: string): string {
  return existsSync(path) ? readFileSync(path, 'utf8') : '';
}

async function main(): Promise<void> {
  const checkOnly = process.argv.includes('--check');

  const merged = new Map<string, BrandLogo>();
  collectLogos(merged);
  validateCoverage(merged);
  validateGroupsAndRanks(merged);
  validateLetterTile();
  validateNavIcon();

  let client = '';
  let host = '';
  try {
    client = await buildClient();
    host = await buildHost();
  } catch (error) {
    problems.push(`esbuild failed: ${error instanceof Error ? error.message : String(error)}`);
  }
  if (client !== '') validateClientBundle(client);

  for (const problem of problems) console.error('error: ' + problem);
  if (problems.length > 0) process.exit(1);
  for (const warning of warnings) console.warn('warning: ' + warning);

  const artifacts: ReadonlyArray<{ path: string; text: string; name: string }> = [
    { path: CLIENT_OUT, text: client, name: 'client.js' },
    { path: HOST_OUT, text: host, name: 'index.js' },
  ];

  if (checkOnly) {
    let stale = false;
    for (const artifact of artifacts) {
      if (readArtifact(artifact.path) !== artifact.text) {
        stale = true;
        console.error(`error: ${artifact.name} is missing or stale — run \`pnpm run build\``);
      }
    }
    if (stale) process.exit(1);
    console.log(
      `artifacts are up to date (${merged.size} logos, client.js ${client.length} bytes, index.js ${host.length} bytes)`,
    );
    return;
  }

  for (const artifact of artifacts) {
    writeFileSync(artifact.path, artifact.text);
    console.log(`wrote ${artifact.name}: ${artifact.text.length} bytes`);
  }
  console.log(
    `artwork: ${merged.size} logos, ${VENDOR_RULES.length} vendor rules, ${Object.keys(VENDOR_CHANNELS).length} channels`,
  );
}

await main();
